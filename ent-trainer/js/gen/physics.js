import { num, need } from './util.js';

const S = 'physics';

// пары сопротивлений с целым общим: R1 * R2 делится на R1 + R2
const PAR = [];
for (let x = 2; x <= 60; x++) for (let y = x; y <= 60; y++) if ((x * y) % (x + y) === 0) PAR.push([x, y, (x * y) / (x + y)]);
// линза: F, d, f с целым f
const LENS = [];
for (let F = 5; F <= 30; F += 5) for (let d = F + 5; d <= 90; d += 5) if ((F * d) % (d - F) === 0) LENS.push([F, d, (F * d) / (d - F)]);

